function normalizeEffects(effects) {
  return Object.keys(effects).reduce((result, key) => {
    if (["tech", "communication", "energy", "savings", "influence"].includes(key)) {
      result[key] = Math.trunc(effects[key]);
    }
    return result;
  }, {});
}

function buildChoice(eventId, sceneItem, stageIndex, eventIndex, choiceIndex) {
  const outcomeSet = OUTCOME_SETS[(stageIndex * 3 + eventIndex) % OUTCOME_SETS.length];
  const effectSet = EFFECT_PATTERNS[(stageIndex + eventIndex) % EFFECT_PATTERNS.length];
  const approachTags = ["直面", "权衡", "边界"];
  return Object.freeze({
    id: `${eventId}_${String.fromCharCode(97 + choiceIndex)}`,
    text: sceneItem.actions[choiceIndex],
    tags: Object.freeze([
      sceneItem.category,
      approachTags[choiceIndex],
      sceneItem.dramatic ? "复合冲突" : "职业判断"
    ]),
    outcome: outcomeSet[choiceIndex],
    effects: Object.freeze(normalizeEffects(effectSet[choiceIndex]))
  });
}

function buildEvents() {
  return STAGES.reduce((allEvents, stage, stageIndex) => {
    const scenes = STAGE_SCENES[stageIndex];
    scenes.forEach((sceneItem, eventIndex) => {
      const eventId = `s${stage.number}_t${String(eventIndex + 1).padStart(2, "0")}`;
      allEvents.push(Object.freeze({
        id: eventId,
        stageId: stage.id,
        kind: "pool",
        category: sceneItem.category,
        title: sceneItem.title,
        body: sceneItem.body,
        choices: Object.freeze([0, 1, 2].map((choiceIndex) => (
          buildChoice(eventId, sceneItem, stageIndex, eventIndex, choiceIndex)
        )))
      }));
    });
    return allEvents;
  }, []);
}

const TRIPLE_EXPANSION_EVENTS = Object.freeze(buildEvents());

