const STAGE_SCENARIOS = [
  ["onboarding", onboardingScenarios],
  ["release", releaseScenarios],
  ["frontline", frontlineScenarios],
  ["crossroad", crossroadScenarios],
  ["performance", performanceScenarios]
];

const TRIPLE_EXPANSION_EVENTS = STAGE_SCENARIOS.reduce((events, entry) => {
  const stageId = entry[0];
  const scenarios = entry[1];

  scenarios.forEach((item, index) => {
    const eventId = `hx-${stageId}-${String(index + 1).padStart(2, "0")}`;
    events.push({
      id: eventId,
      stageId,
      termId: item.termId,
      title: item.title,
      situation: item.dramatic ? `【虚构复合情景】${item.situation.replace(/^虚构复合情景：/, "")}` : item.situation,
      choices: item.choices.map((itemChoice) => ({
        id: `${eventId}-${itemChoice.key}`,
        text: itemChoice.text,
        outcome: itemChoice.outcome,
        effects: itemChoice.effects,
        tags: itemChoice.tags.slice()
      }))
    });
  });

  return events;
}, []);

module.exports = TRIPLE_EXPANSION_EVENTS;
Object.defineProperty(module.exports, "TRIPLE_EXPANSION_EVENTS", {
  value: TRIPLE_EXPANSION_EVENTS,
  enumerable: false
});
